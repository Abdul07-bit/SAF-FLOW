/**
 * Writes the API reference from the live route registry:
 *   docs/openapi.json  - OpenAPI 3.1
 *   docs/API.md        - endpoint list with each route's authorization policy
 *
 *   npm run docs:api
 *
 * Importing the registry opens no database connection, so this runs anywhere.
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { listRoutes } from "../src/server/api";
import { buildOpenApi, describePolicy } from "../src/server/openapi";

const routes = listRoutes();
mkdirSync("docs", { recursive: true });
writeFileSync("docs/openapi.json", JSON.stringify(buildOpenApi(routes), null, 2) + "\n");

const TAG_TITLES: Record<string, string> = {
  auth: "Authentication & session", admin: "Super Admin", team: "Staff logins & roles", staff: "Employee records (Growth)", attendance: "Attendance (Growth)",
  "id-cards": "ID cards & QR verification (Growth)", settings: "Settings", billing: "Subscription & SAF billing",
  support: "Support", "day-book": "Day book, expenses & daily report", dine: "SAF Dine Flow", stay: "SAF Stay Flow", bill: "SAF Bill Flow", public: "Public (no sign-in)", system: "System",
};
const ORDER = Object.keys(TAG_TITLES);

const byTag = new Map<string, typeof routes>();
for (const r of routes) {
  const tag = r.tag ?? "api";
  if (!byTag.has(tag)) byTag.set(tag, []);
  byTag.get(tag)!.push(r);
}
const tags = [...byTag.keys()].sort((a, b) => (ORDER.indexOf(a) + 1 || 99) - (ORDER.indexOf(b) + 1 || 99) || a.localeCompare(b));

const md: string[] = [
  "# SMARTAUTO FLEX API reference",
  "",
  "Generated by `npm run docs:api` from the route registry - do not edit by hand.",
  "The machine-readable version is [openapi.json](openapi.json), also served at `GET /api/docs/openapi.json`.",
  "",
  "## Conventions",
  "",
  "- Base path: `/api`. JSON in, JSON out. Money is in paise (integer); percentages are basis points; dates are `YYYY-MM-DD` (IST).",
  "- Sign in with `POST /api/auth/login`; the response sets the HttpOnly `saf_session` cookie used by every other call.",
  "- Every non-GET request from a signed-in user must send the header `x-saf-request: 1` (CSRF guard).",
  "- Product routes written as `/:product/...` exist for `dine`, `stay` and `bill`; the product in the URL is authorised like any other.",
  "- Branch-scoped data uses the `x-saf-branch` header (defaults to the main branch).",
  "- Errors: `{ \"error\": { \"code\", \"message\", \"details\"? } }` with status 400 (validation), 401 (not signed in), 402 (subscription expired),",
  "  403 (plan feature / role permission / suspended), 404, 409 (conflict), 429 (rate limited).",
  "",
  "## Authorization column",
  "",
  "Each endpoint declares exactly one policy, enforced by the router before the handler runs:",
  "",
  "- **Public** - no session. Used only for the QR menu, public invoices, staff ID verification, webhooks and health.",
  "- **Any signed-in user** - session only.",
  "- **SAF Super Admin only** - platform account.",
  "- **Tenant user of a product** - checks, in order: business active, product subscribed, subscription usable,",
  "  the user has a role in that product, the plan (or a per-business override) includes the feature, the role grants the permission.",
  "",
  `${routes.length} endpoints.`,
  "",
];
for (const tag of tags) {
  md.push(`## ${TAG_TITLES[tag] ?? tag}`, "", "| Method | Path | Summary | Authorization |", "|---|---|---|---|");
  for (const r of byTag.get(tag)!.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method)))
    md.push(`| ${r.method} | \`/api${r.path}\` | ${r.summary.replace(/\|/g, "\|")} | ${describePolicy(r).replace(/\|/g, "or")} |`);
  md.push("");
}
writeFileSync("docs/API.md", md.join("\n"));
console.log(`Wrote docs/openapi.json and docs/API.md (${routes.length} endpoints).`);
process.exit(0);
